// Writes the start page's diagram as a standalone SVG for the README,
// docs/diagrams/flume.svg: its own palette, light or dark by the
// reader's system setting, animated inside an <img> on GitHub.
//
//   bun run readme-diagram
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { hero } from "../src/diagrams/hero";

const out = resolve(dirname(fileURLToPath(import.meta.url)), "../../docs/diagrams/flume.svg");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `<!-- Generated by site/scripts/readme-diagram.ts from site/src/diagrams/hero.ts; edit those, not this file. -->\n` +
    hero("wide", { id: "fl", standalone: true }),
);
console.log(`wrote ${out}`);
